"""LongBench v2 (THUDM/LongBench-v2) on the <= 120k-token subset, official zero-shot
prompt and answer extraction (THUDM/LongBench prompts/0shot.txt, pred.py).

The subset is the list in subset_120k.json (generated by make_subset.py: every
question whose context is at most 122880 Kimi Linear tokens, all six domains); the
docs are filtered by `_id`, so both arms see exactly the same prompts. Deviation from
the official runner: greedy decoding (the official script samples at T=0.1) and a
raw /v1/completions prompt (no chat template), the same choices as the RULER line.
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SUBSET = os.path.join(HERE, "subset_120k.json")

PROMPT = (
    "Please read the following text and answer the question below.\n\n"
    "<text>\n{context}\n</text>\n\n"
    "What is the correct answer to this question: {question}\n"
    "Choices:\n(A) {a}\n(B) {b}\n(C) {c}\n(D) {d}\n\n"
    'Format your response as follows: "The correct answer is (insert answer here)".'
)


def _subset_ids():
    with open(SUBSET) as f:
        return {row["_id"] for row in json.load(f)["rows"]}


def process_docs(dataset):
    ids = _subset_ids()
    return dataset.filter(lambda d: d["_id"] in ids)


def doc_to_text(doc):
    return PROMPT.format(context=doc["context"], question=doc["question"].strip(),
                         a=doc["choice_A"], b=doc["choice_B"], c=doc["choice_C"], d=doc["choice_D"])


def doc_to_target(doc):
    return doc["answer"]


def extract_answer(response):  # verbatim rule of THUDM/LongBench pred.py
    response = response.replace("*", "")
    m = re.search(r"The correct answer is \(([A-D])\)", response)
    if m:
        return m.group(1)
    m = re.search(r"The correct answer is ([A-D])", response)
    return m.group(1) if m else None


def process_results(doc, results):
    pred = extract_answer(results[0])
    return {"acc": 1.0 if pred == doc["answer"] else 0.0,
            "parsed": 1.0 if pred is not None else 0.0}
