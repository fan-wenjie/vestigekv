"""LongBench v2 (THUDM/LongBench-v2) on the <= 120k-token subset: the prompt of
upstream lm-eval's own longbench2 task, whose four one-token choices A/B/C/D are
scored at the "Answer:" position rather than generated.

The subset is the list in subset_120k.json (generated by make_subset.py: every
question whose context is at most 122880 Kimi Linear tokens, all six domains); the
docs are filtered by `_id`, so both arms see exactly the same prompts. Deviations
from the official runner: greedy rather than T=0.1, and scoring rather than
generation -- this model reasons before answering and does not reach the answer
line inside 128 tokens (measured: 1% of 300 parsed, both arms at the floor).

run_longbench2.py reads the four scores from one top-k request instead of four
echo requests; see its docstring and prereg3 amendment 1.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SUBSET = os.path.join(HERE, "subset_120k.json")

# Upstream's prompt, ending at "Answer:" because the four choices are scored
# rather than generated (lm_eval/tasks/longbench2/_longbench_common_yaml).
PROMPT = (
    "Please read the following text and answer the question below.\n\n"
    "<text>\n{context}\n</text>\n\n"
    "What is the correct answer to this question: {question}\n"
    "Choices:\n(A) {a}\n(B) {b}\n(C) {c}\n(D) {d}\n\n"
    "Answer:"
)


def _subset_ids():
    with open(SUBSET) as f:
        return {row["_id"] for row in json.load(f)["rows"]}


def process_docs(dataset):
    ids = _subset_ids()
    return dataset.filter(lambda d: d["_id"] in ids)


def doc_to_text(doc):
    return PROMPT.format(context=doc["context"], question=doc["question"].strip(),
                         a=doc["choice_A"], b=doc["choice_B"], c=doc["choice_C"], d=doc["choice_D"])


def doc_to_target(doc):
    return "ABCD".index(doc["answer"])
